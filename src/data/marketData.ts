// Helper to generate realistic price histories
function generateHistory(basePrice: number, pointsCount: number, volatilityPercent: number, trend: number): PricePoint[] {
  const points: PricePoint[] = [];
  let currentPrice = basePrice * (1 - (trend / 100));
  const startTime = Date.now() - pointsCount * 15 * 60 * 1000;

  for (let i = 0; i < pointsCount; i++) {
    const time = new Date(startTime + i * 15 * 60 * 1000).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const change = (Math.random() - 0.48) * (volatilityPercent / 100) * currentPrice;
    currentPrice = Math.max(0.01, currentPrice + change);
    const open = currentPrice - (Math.random() - 0.5) * 2;
    const high = Math.max(open, currentPrice) + Math.random() * 1.5;
    const low = Math.min(open, currentPrice) - Math.random() * 1.5;
    const volume = Math.floor(Math.random() * 50000) + 10000;

    points.push({
      time,
      price: Number(currentPrice.toFixed(2)),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      volume,
    });
  }
  return points;
}

function generateSparkline(history: PricePoint[]): number[] {
  const step = Math.max(1, Math.floor(history.length / 12));
  return history.filter((_, idx) => idx % step === 0).map(p => p.price);
}

